'use client'

import { useState, useEffect, useCallback } from 'react'
import { Button } from '@/components/ui/button'
import { Input } from '@/components/ui/input'
import { Label } from '@/components/ui/label'
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from '@/components/ui/card'
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@/components/ui/select'
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from '@/components/ui/table'
import type { Receipt } from '@/lib/types'

export default function ReportsPage() {
  const [staffName, setStaffName] = useState<string>('')
  const [receipts, setReceipts] = useState<Receipt[]>([])
  const [loading, setLoading] = useState(true)
  const [dateFrom, setDateFrom] = useState('')
  const [dateTo, setDateTo] = useState('')
  const [statusFilter, setStatusFilter] = useState('all')
  const [staffFilter, setStaffFilter] = useState('all')
  const [staffList, setStaffList] = useState<{ id: string; full_name: string }[]>([])
  const [exporting, setExporting] = useState<string | null>(null)
  const [analytics, setAnalytics] = useState<{
    totalDiscountsGiven: number
    discountsByCode: Record<string, { count: number; total: number }>
    topDiscountStaff: { name: string; count: number } | null
    discountedReceiptsCount: number
    revenueByCategory: Record<string, number>
    freeBenefitsUsed: Record<string, number>
  } | null>(null)

  const fetchReceipts = useCallback(async () => {
    setLoading(true)
    try {
      const params = new URLSearchParams()
      if (dateFrom) params.set('dateFrom', dateFrom)
      if (dateTo) params.set('dateTo', dateTo)
      if (statusFilter !== 'all') params.set('status', statusFilter)
      if (staffFilter !== 'all') params.set('staffId', staffFilter)

      const res = await fetch(`/api/reports?${params.toString()}`)
      if (res.ok) {
        const data = await res.json()
        setReceipts(data.receipts)
        setStaffList(data.staffList || [])
        if (data.staffName) setStaffName(data.staffName)
        if (data.analytics) setAnalytics(data.analytics)
      }
    } catch {
      // Handle error silently
    } finally {
      setLoading(false)
    }
  }, [dateFrom, dateTo, statusFilter, staffFilter])

  useEffect(() => {
    fetchReceipts()
  }, [fetchReceipts])

  const filtered = receipts
  const activeStatuses = ['Issued', 'Printed', 'Emailed', 'Verified']
  const totalAmount = filtered.filter(r => activeStatuses.includes(r.status)).reduce((s, r) => s + Number(r.amount), 0)
  const totalReceipts = filtered.length
  const cancelledCount = filtered.filter(r => r.status === 'Cancelled').length

  const handleExportCSV = async () => {
    setExporting('csv')
    try {
      const headers = ['Receipt #', 'Status', 'Client', 'Service', 'Amount (SLE)', 'Payment Method', 'Issued By', 'Date']
      const rows = filtered.map(r => [
        r.receipt_number,
        r.status,
        r.customer_name,
        `"${r.service_description.replace(/"/g, '""')}"`,
        r.amount.toFixed(2),
        r.payment_method,
        r.issuer_name,
        new Date(r.issued_at).toLocaleString(),
      ])
      const summaryRows = [
        [],
        ['--- Summary ---'],
        ['Total Receipts', String(totalReceipts)],
        ['Total Amount (SLE)', totalAmount.toFixed(2)],
        ['Cancelled', String(cancelledCount)],
        ['Generated', new Date().toLocaleString()],
        ['Generated By', staffName || ''],
      ]
      const csvContent = [headers.join(','), ...rows.map(r => r.join(',')), ...summaryRows.map(r => r.join(','))].join('\n')
      const blob = new Blob([csvContent], { type: 'text/csv' })
      const url = URL.createObjectURL(blob)
      const a = document.createElement('a')
      a.href = url
      a.download = `receipt-report-${dateFrom || 'all'}-to-${dateTo || 'all'}.csv`
      a.click()
      URL.revokeObjectURL(url)

      // Log export
      await fetch('/api/log-export', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ format: 'CSV', dateFrom, dateTo, count: totalReceipts }),
      })
    } finally {
      setExporting(null)
    }
  }

  const handleExportPDF = async () => {
    setExporting('pdf')
    try {
      const printWindow = window.open('', '_blank')
      if (!printWindow) return

      const tableRows = filtered.map(r => `
        <tr>
          <td style="padding:6px 8px;border-bottom:1px solid #e5e5e5;font-family:monospace;font-size:11px;">${r.receipt_number}</td>
          <td style="padding:6px 8px;border-bottom:1px solid #e5e5e5;"><span style="padding:2px 8px;border-radius:4px;font-size:10px;font-weight:600;${activeStatuses.includes(r.status) ? 'background:#dcfce7;color:#166534;' : r.status === 'Cancelled' ? 'background:#fee2e2;color:#991b1b;' : 'background:#f3f4f6;color:#374151;'}">${r.status}</span></td>
          <td style="padding:6px 8px;border-bottom:1px solid #e5e5e5;">${r.customer_name}</td>
          <td style="padding:6px 8px;border-bottom:1px solid #e5e5e5;text-align:right;font-weight:600;">SLE ${Number(r.amount).toFixed(2)}</td>
          <td style="padding:6px 8px;border-bottom:1px solid #e5e5e5;">${r.payment_method}</td>
          <td style="padding:6px 8px;border-bottom:1px solid #e5e5e5;">${r.issuer_name}</td>
          <td style="padding:6px 8px;border-bottom:1px solid #e5e5e5;font-size:11px;">${new Date(r.issued_at).toLocaleDateString()}</td>
        </tr>
      `).join('')

      printWindow.document.write(`<!DOCTYPE html><html><head><title>Receipt Report</title>
        <style>body{font-family:system-ui,-apple-system,sans-serif;padding:40px;color:#1a1a1a;} 
        table{width:100%;border-collapse:collapse;margin:20px 0;font-size:13px;}
        th{text-align:left;padding:8px;border-bottom:2px solid #1a7fc1;color:#1a7fc1;font-size:11px;text-transform:uppercase;letter-spacing:1px;}
        .header{display:flex;justify-content:space-between;align-items:flex-start;margin-bottom:30px;padding-bottom:20px;border-bottom:2px solid #1a7fc1;}
        .summary{display:grid;grid-template-columns:repeat(3,1fr);gap:16px;margin:20px 0;}
        .summary-card{background:#f8fafc;border:1px solid #e2e8f0;border-radius:8px;padding:16px;}
        .summary-label{font-size:11px;text-transform:uppercase;letter-spacing:1px;color:#64748b;}
        .summary-value{font-size:24px;font-weight:700;color:#0f172a;margin-top:4px;}
        @media print{@page{margin:15mm;size:A4 landscape;}}</style></head>
        <body>
          <div class="header">
            <div><h1 style="margin:0;color:#1a7fc1;font-size:24px;">HOSTech Coworking Space</h1>
            <p style="margin:4px 0 0;color:#64748b;font-size:14px;">Receipt Report</p></div>
            <div style="text-align:right;">
              <p style="margin:0;font-size:12px;color:#64748b;">Period: ${dateFrom || 'All'} to ${dateTo || 'All'}</p>
              <p style="margin:4px 0 0;font-size:12px;color:#64748b;">Generated: ${new Date().toLocaleString()}</p>
              <p style="margin:4px 0 0;font-size:12px;color:#64748b;">By: ${staffName}</p>
            </div>
          </div>
          <div class="summary">
            <div class="summary-card"><div class="summary-label">Total Receipts</div><div class="summary-value">${totalReceipts}</div></div>
            <div class="summary-card"><div class="summary-label">Total Revenue</div><div class="summary-value">SLE ${totalAmount.toFixed(2)}</div></div>
            <div class="summary-card"><div class="summary-label">Cancelled</div><div class="summary-value" style="color:#dc2626;">${cancelledCount}</div></div>
          </div>
          <table><thead><tr>
            <th>Receipt #</th><th>Status</th><th>Client</th><th>Amount</th><th>Payment</th><th>Issued By</th><th>Date</th>
          </tr></thead><tbody>${tableRows}</tbody>
          <tfoot><tr style="font-weight:700;border-top:2px solid #1a7fc1;">
            <td style="padding:10px 8px;" colspan="3">TOTAL</td>
            <td style="padding:10px 8px;text-align:right;">SLE ${totalAmount.toFixed(2)}</td>
            <td colspan="3"></td>
          </tr></tfoot></table>
        </body></html>`)
      printWindow.document.close()
      setTimeout(() => printWindow.print(), 300)

      // Log export
      await fetch('/api/log-export', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ format: 'PDF', dateFrom, dateTo, count: totalReceipts }),
      })
    } finally {
      setExporting(null)
    }
  }

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-bold text-foreground">Reports</h1>
        <p className="text-muted-foreground">View and export receipt reports</p>
      </div>

      {/* Filters */}
      <Card>
        <CardHeader>
          <CardTitle className="text-foreground text-base">Filters</CardTitle>
          <CardDescription>Narrow down the report data</CardDescription>
        </CardHeader>
        <CardContent>
          <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
            <div className="space-y-2">
              <Label className="text-foreground">From Date</Label>
              <Input type="date" value={dateFrom} onChange={e => setDateFrom(e.target.value)} />
            </div>
            <div className="space-y-2">
              <Label className="text-foreground">To Date</Label>
              <Input type="date" value={dateTo} onChange={e => setDateTo(e.target.value)} />
            </div>
            <div className="space-y-2">
              <Label className="text-foreground">Status</Label>
              <Select value={statusFilter} onValueChange={setStatusFilter}>
                <SelectTrigger><SelectValue /></SelectTrigger>
                <SelectContent>
                  <SelectItem value="all">All Statuses</SelectItem>
                  <SelectItem value="Draft">Draft</SelectItem>
                  <SelectItem value="Issued">Issued</SelectItem>
                  <SelectItem value="Printed">Printed</SelectItem>
                  <SelectItem value="Emailed">Emailed</SelectItem>
                  <SelectItem value="Verified">Verified</SelectItem>
                  <SelectItem value="Cancelled">Cancelled</SelectItem>
                  <SelectItem value="Synced">Synced</SelectItem>
                </SelectContent>
              </Select>
            </div>
            <div className="space-y-2">
              <Label className="text-foreground">Staff</Label>
              <Select value={staffFilter} onValueChange={setStaffFilter}>
                <SelectTrigger><SelectValue /></SelectTrigger>
                <SelectContent>
                  <SelectItem value="all">All Staff</SelectItem>
                  {staffList.map(s => (
                    <SelectItem key={s.id} value={s.id}>{s.full_name}</SelectItem>
                  ))}
                </SelectContent>
              </Select>
            </div>
          </div>
        </CardContent>
      </Card>

      {/* Summary Cards */}
      <div className="grid gap-4 sm:grid-cols-3">
        <Card>
          <CardContent className="pt-6">
            <p className="text-xs uppercase tracking-wider text-muted-foreground">Total Receipts</p>
            <p className="text-3xl font-bold text-foreground mt-1">{totalReceipts}</p>
          </CardContent>
        </Card>
        <Card>
          <CardContent className="pt-6">
            <p className="text-xs uppercase tracking-wider text-muted-foreground">Total Revenue</p>
            <p className="text-3xl font-bold text-[#1a7fc1] mt-1">SLE {totalAmount.toFixed(2)}</p>
          </CardContent>
        </Card>
        <Card>
          <CardContent className="pt-6">
            <p className="text-xs uppercase tracking-wider text-muted-foreground">Cancelled</p>
            <p className="text-3xl font-bold text-red-600 mt-1">{cancelledCount}</p>
          </CardContent>
        </Card>
      </div>

      {/* Enhanced Analytics */}
      {analytics && (
        <div className="grid gap-4 md:grid-cols-2">
          {/* Discount Summary */}
          <Card>
            <CardHeader className="pb-3">
              <CardTitle className="text-base text-foreground">Discount Summary</CardTitle>
              <CardDescription>Discount usage and revenue impact</CardDescription>
            </CardHeader>
            <CardContent className="space-y-3">
              <div className="grid grid-cols-2 gap-3">
                <div className="bg-muted/50 rounded-lg p-3">
                  <p className="text-xs text-muted-foreground uppercase tracking-wider">Total Discounts Given</p>
                  <p className="text-lg font-bold text-foreground">NLe {analytics.totalDiscountsGiven.toFixed(2)}</p>
                </div>
                <div className="bg-muted/50 rounded-lg p-3">
                  <p className="text-xs text-muted-foreground uppercase tracking-wider">Discounted Receipts</p>
                  <p className="text-lg font-bold text-foreground">{analytics.discountedReceiptsCount}</p>
                </div>
              </div>
              {Object.keys(analytics.discountsByCode).length > 0 && (
                <div>
                  <p className="text-xs font-medium text-muted-foreground uppercase tracking-wider mb-2">By Discount Code</p>
                  <div className="space-y-1">
                    {Object.entries(analytics.discountsByCode).map(([code, data]) => (
                      <div key={code} className="flex items-center justify-between text-sm bg-muted/30 rounded px-3 py-1.5">
                        <span className="font-mono text-xs font-medium">{code}</span>
                        <span className="text-muted-foreground">{data.count}x | NLe {data.total.toFixed(2)}</span>
                      </div>
                    ))}
                  </div>
                </div>
              )}
              {analytics.topDiscountStaff && (
                <div className="bg-muted/30 rounded-lg p-3">
                  <p className="text-xs text-muted-foreground uppercase tracking-wider">Most Discounts Applied By</p>
                  <p className="text-sm font-medium text-foreground">{analytics.topDiscountStaff.name} ({analytics.topDiscountStaff.count} receipts)</p>
                </div>
              )}
            </CardContent>
          </Card>

          {/* Revenue by Service Category */}
          <Card>
            <CardHeader className="pb-3">
              <CardTitle className="text-base text-foreground">Revenue by Category</CardTitle>
              <CardDescription>Breakdown by service type</CardDescription>
            </CardHeader>
            <CardContent className="space-y-3">
              {Object.keys(analytics.revenueByCategory).length > 0 ? (
                <div className="space-y-2">
                  {Object.entries(analytics.revenueByCategory)
                    .sort(([, a], [, b]) => b - a)
                    .map(([category, amount]) => {
                      const total = Object.values(analytics.revenueByCategory).reduce((s, v) => s + v, 0)
                      const percentage = total > 0 ? (amount / total * 100).toFixed(1) : '0'
                      const categoryLabels: Record<string, string> = {
                        workspace: 'Workspace',
                        meeting_room: 'Meeting Room',
                        conference_room: 'Conference Room',
                        printing: 'Printing & Copying',
                        custom: 'Custom',
                        Other: 'Other/Legacy',
                      }
                      return (
                        <div key={category}>
                          <div className="flex items-center justify-between text-sm mb-1">
                            <span className="font-medium text-foreground">{categoryLabels[category] || category}</span>
                            <span className="text-muted-foreground">NLe {amount.toFixed(2)} ({percentage}%)</span>
                          </div>
                          <div className="h-2 bg-muted rounded-full overflow-hidden">
                            <div
                              className="h-full bg-[#1a7fc1] rounded-full transition-all"
                              style={{ width: `${percentage}%` }}
                            />
                          </div>
                        </div>
                      )
                    })}
                </div>
              ) : (
                <p className="text-sm text-muted-foreground">No category data available yet.</p>
              )}
              {Object.keys(analytics.freeBenefitsUsed).length > 0 && (
                <div className="border-t pt-3">
                  <p className="text-xs font-medium text-muted-foreground uppercase tracking-wider mb-2">Free Benefits Used</p>
                  <div className="space-y-1">
                    {Object.entries(analytics.freeBenefitsUsed).map(([type, count]) => {
                      const labels: Record<string, string> = {
                        meeting_room: 'Free Meeting Hours',
                        conference_room: 'Free Conference Hours',
                        printing: 'Free Print Pages',
                      }
                      return (
                        <div key={type} className="flex items-center justify-between text-sm">
                          <span className="text-muted-foreground">{labels[type] || type}</span>
                          <span className="font-medium text-foreground">{count}</span>
                        </div>
                      )
                    })}
                  </div>
                </div>
              )}
            </CardContent>
          </Card>
        </div>
      )}

      {/* Export Buttons */}
      <div className="flex flex-wrap gap-3">
        <Button onClick={handleExportCSV} disabled={exporting !== null || filtered.length === 0} variant="outline" className="gap-2 bg-transparent">
          <svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"><path d="M14.5 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V7.5L14.5 2z" /><polyline points="14 2 14 8 20 8" /></svg>
          {exporting === 'csv' ? 'Exporting...' : 'Export CSV'}
        </Button>
        <Button onClick={handleExportPDF} disabled={exporting !== null || filtered.length === 0} variant="outline" className="gap-2 bg-transparent">
          <svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"><path d="M14.5 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V7.5L14.5 2z" /><polyline points="14 2 14 8 20 8" /><line x1="16" x2="8" y1="13" y2="13" /><line x1="16" x2="8" y1="17" y2="17" /></svg>
          {exporting === 'pdf' ? 'Exporting...' : 'Export PDF'}
        </Button>
      </div>

      {/* Results Table */}
      <Card>
        <CardContent className="p-0">
          {loading ? (
            <div className="flex items-center justify-center py-12">
              <p className="text-muted-foreground">Loading report data...</p>
            </div>
          ) : filtered.length === 0 ? (
            <div className="flex items-center justify-center py-12">
              <p className="text-muted-foreground">No receipts found for the selected filters.</p>
            </div>
          ) : (
            <div className="overflow-x-auto">
              <Table>
                <TableHeader>
                  <TableRow>
                    <TableHead>Receipt #</TableHead>
                    <TableHead>Status</TableHead>
                    <TableHead>Client</TableHead>
                    <TableHead className="text-right">Amount</TableHead>
                    <TableHead>Payment</TableHead>
                    <TableHead>Issued By</TableHead>
                    <TableHead>Date</TableHead>
                  </TableRow>
                </TableHeader>
                <TableBody>
                  {filtered.map(r => (
                    <TableRow key={r.id}>
                      <TableCell className="font-mono text-xs">{r.receipt_number}</TableCell>
                      <TableCell>
                        <span className={`inline-block px-2 py-0.5 rounded-full text-xs font-medium ${
                          activeStatuses.includes(r.status) ? 'bg-green-100 text-green-800' :
                          r.status === 'Cancelled' ? 'bg-red-100 text-red-800' :
                          r.status === 'Draft' ? 'bg-gray-100 text-gray-800' :
                          'bg-blue-100 text-blue-800'
                        }`}>
                          {r.status}
                        </span>
                      </TableCell>
                      <TableCell>{r.customer_name}</TableCell>
                      <TableCell className="text-right font-medium">SLE {Number(r.amount).toFixed(2)}</TableCell>
                      <TableCell>{r.payment_method}</TableCell>
                      <TableCell>{r.issuer_name}</TableCell>
                      <TableCell className="text-xs">{new Date(r.issued_at).toLocaleDateString()}</TableCell>
                    </TableRow>
                  ))}
                </TableBody>
              </Table>
            </div>
          )}
        </CardContent>
      </Card>
    </div>
  )
}
